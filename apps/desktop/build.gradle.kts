// The Android app's icons, pictures, fonts and text files, so both apps look the same.
val androidMain = rootProject.file("apps/android-tv/src/main")
tasks.processResources {
    from(androidMain.resolve("res")) {
        include("drawable*/**", "font/**")
        // drawable-nodpi/logo.webp → drawable/logo.webp (names are unique across folders)
        eachFile { path = path.replace(Regex("^drawable-[a-z]+/"), "drawable/") }
        includeEmptyDirs = false
    }
    from(androidMain.resolve("assets")) { into("assets") }
}

// A small R object with the same names as Android's (R.drawable.ic_star, R.font.inter_bold),
// so the shared screens compile unchanged here. DesktopRes maps each id back to its file.
val genR by tasks.registering {
    val out = layout.buildDirectory.dir("generated/sparky")
    inputs.dir(androidMain.resolve("res"))
    inputs.property("version", "$appVersion/$buildNumber")
    outputs.dir(out)
    doLast {
        val res = androidMain.resolve("res")
        val drawables = res.listFiles()!!.filter { it.isDirectory && it.name.startsWith("drawable") }
            .flatMap { it.listFiles()!!.toList() }.filter { it.isFile }.sortedBy { it.name }
        val fonts = res.resolve("font").listFiles()!!.filter { it.isFile }.sortedBy { it.name }
        val sb = StringBuilder("package com.sparky.iptv\n\n// Generated by apps/desktop/build.gradle.kts (genR). Don't edit.\n")
        sb.append("object R {\n    object drawable {\n")
        drawables.forEachIndexed { i, f -> sb.append("        const val ${f.nameWithoutExtension} = ${1000 + i}\n") }
        sb.append("    }\n    object font {\n")
        fonts.forEachIndexed { i, f -> sb.append("        const val ${f.nameWithoutExtension} = ${2000 + i}\n") }
        sb.append("    }\n}\n\nobject DesktopRes {\n    val paths: Map<Int, String> = mapOf(\n")
        drawables.forEachIndexed { i, f -> sb.append("        ${1000 + i} to \"drawable/${f.name}\",\n") }
        fonts.forEachIndexed { i, f -> sb.append("        ${2000 + i} to \"font/${f.name}\",\n") }
        sb.append("    )\n    const val VERSION = \"$appVersion (build $buildNumber)\"\n    const val BUILD = $buildNumber\n}\n")
        val dir = out.get().asFile.resolve("com/sparky/iptv")
        dir.mkdirs()
        dir.resolve("R.kt").writeText(sb.toString())
    }
}
tasks.named("compileKotlin") { dependsOn(genR) }

